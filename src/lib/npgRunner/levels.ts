/** Join a level's chunks into one map of ROWS equal-length rows. */
export function buildMap(def: LevelDef): string[] {
  const rows: string[] = Array.from({ length: ROWS }, () => '');
  for (const chunk of def.chunks) {
    const lines = chunk.replace(/^\n/, '').split('\n');
    if (lines.length !== ROWS) throw new Error(`${def.id}: chunk has ${lines.length} rows, expected ${ROWS}`);
    const w = Math.max(...lines.map((l) => l.length));
    for (let r = 0; r < ROWS; r++) rows[r] += lines[r].padEnd(w, '.');
  }
  return rows;
}
